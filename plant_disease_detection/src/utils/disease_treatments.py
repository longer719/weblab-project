    def get_plant_info(self, plant_type: str) -> Dict[str, Any]:
        """
        获取植物的详细信息（不包括病害信息）(保持原有逻辑)
        Args:
            plant_type: 植物类型名称
        Returns:
            植物信息字典
        """
        plant, _ = self.map_dataset_class_to_db(plant_type)
        plant_norm = self._normalize_name(plant)

        if not plant or plant_norm not in self.treatments:
            logger.warning(f"请求的植物 '{plant_type}' (映射为 '{plant}') 不在数据库中。")
            return {
                "plant_name": plant or plant_type,
                "error": f"未找到关于 {plant or plant_type} 的详细信息。",
                "description": "请确保植物名称正确或已被系统支持。",
                "general_care": [],
                "common_diseases": []
            }

        overview = self.treatments[plant_norm].get("overview", {})
        common_diseases = sorted([
            disease for disease in self.treatments[plant_norm]
            if disease != "overview" and disease != "健康"
        ])
        result_plant_name = plant or plant_type

        return {
            "plant_name": result_plant_name,
            "description": overview.get("description", f"{result_plant_name} 的概述信息待补充。"),
            "general_care": overview.get("general_care", []),
            "detailed_info": overview.get("detailed_info", {}),
            "common_diseases": common_diseases
        }

    def is_disease_compatible_with_plant(self, plant_type: str, disease_class_name: str) -> bool:
        """检查病害是否与植物兼容 (保持原有逻辑)"""
        mapped_plant, mapped_disease = self.map_dataset_class_to_db(disease_class_name)
        normalized_input_plant = self._normalize_name(plant_type)
        normalized_mapped_plant = self._normalize_name(mapped_plant)
        normalized_mapped_disease = self._normalize_name(mapped_disease)

        if normalized_mapped_plant and normalized_mapped_plant == normalized_input_plant:
            if normalized_mapped_disease == "健康":
                return True
            if normalized_input_plant in self.treatments and normalized_mapped_disease in self.treatments[normalized_input_plant]:
                return True

        potential_disease_name = self._normalize_name(disease_class_name)
        if normalized_input_plant in self.treatments and potential_disease_name in self.treatments[normalized_input_plant]:
            return True

        if potential_disease_name == "健康" or normalized_mapped_disease == "健康":
            return True

        # logger.warning(f"无法明确判断病害 '{disease_class_name}' 与植物 '{plant_type}' 的兼容性，采取宽松处理，认为兼容。")
        return True # 保持宽松处理