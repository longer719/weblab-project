# from src.utils.mapping_service import MappingService

logger = logging.getLogger(__name__)

class DiseaseTreatmentDatabase:
    """植物病害治疗建议数据库"""

    def __init__(self):
        """初始化数据库"""
        # 使用统一的映射服务 (如果你的项目中有这个服务)
        # try:
        #     from src.utils.mapping_service import MappingService
        #     self.mapping_service = MappingService()
        # except ImportError:
        #     logger.warning("MappingService 未找到，将使用简单映射逻辑。")
        #     self.mapping_service = None # 或者提供一个兼容的简单实现
        self.mapping_service = None # 暂时禁用，以确保使用下面的简单映射

        # 构建数据库结构：植物类型 -> 病害类型 -> 治疗信息
        self.treatments = self._initialize_database()

    def get_treatment(self, plant_type: str, disease_type: Optional[str] = None) -> Dict[str, Any]:
        """
        获取特定植物和病害的治疗建议 (保持原有逻辑)
        Args:
            plant_type: 植物类型名称（如"苹果"、"番茄"）或数据集类名（如"Corn___healthy"）
            disease_type: 病害类型名称（如"黑星病"），若为None则返回该植物所有病害
        Returns:
            包含治疗信息的字典
        """
        # 检查是否为数据集类名格式（包含___或-）
        plant, disease = self.map_dataset_class_to_db(plant_type)
        if disease: # 如果输入本身是 plant-disease 组合
            plant_type_to_use = plant
            disease_type_to_use = disease
        else: # 输入只是植物名
            plant_type_to_use = plant
            disease_type_to_use = disease_type

        # 标准化输入
        plant_norm = self._normalize_name(plant_type_to_use)

        if plant_norm not in self.treatments:
            logger.warning(f"植物 '{plant_type_to_use}' 不在治疗数据库中")
            return {"error": f"未找到'{plant_type_to_use}'的治疗信息", "plant_name": plant_type_to_use}

        if disease_type_to_use is None:
            # 返回植物概览和该植物下的病害列表
            plant_data = self.treatments[plant_norm]
            overview = plant_data.get("overview", {})
            diseases_list = sorted([k for k in plant_data.keys() if k != "overview"])
            return {
                "plant_name": plant_type_to_use,
                "overview": overview,
                "diseases": diseases_list
            }

        disease_norm = self._normalize_name(disease_type_to_use)

        if disease_norm not in self.treatments[plant_norm]:
            logger.warning(f"病害 '{disease_type_to_use}' 不在 '{plant_type_to_use}' 的治疗数据库中")
            return {"error": f"未找到'{plant_type_to_use}'的'{disease_type_to_use}'病害治疗信息",
                    "plant_name": plant_type_to_use,
                    "disease_name": disease_type_to_use}

        result = self.treatments[plant_norm][disease_norm].copy()
        result["plant_name"] = plant_type_to_use
        result["disease_name"] = disease_type_to_use
        return result

    def get_supported_plants(self) -> List[str]:
        """获取支持的植物列表 (保持原有逻辑)"""
        return sorted(list(self.treatments.keys()))

    def get_supported_diseases(self, plant_type: Optional[str] = None) -> List[str]:
        """获取支持的病害列表 (保持原有逻辑)"""
        if plant_type is None:
            all_diseases = set()
            for plant in self.treatments:
                plant_diseases = {d for d in self.treatments[plant].keys() if d != "overview"}
                all_diseases.update(plant_diseases)
            return sorted(list(all_diseases))
        else:
            plant = self._normalize_name(plant_type)
            if plant not in self.treatments:
                logger.warning(f"植物 '{plant_type}' 不在治疗数据库中")
                return []
            return sorted([d for d in self.treatments[plant].keys() if d != "overview"])

    def _normalize_name(self, name: Optional[str]) -> str:
        """规范化名称以便比较 (小写, 去首尾空格) (保持原有逻辑)"""
        if name is None:
            return ""
        # 简单处理，将英文映射名中的逗号和括号去除，便于后续查找
        name = name.replace(', including sour', '').replace(', bell', '').replace(' (black measles)', '').replace(' (citrus greening)', '').replace(' (isariopsis leaf spot)', '').replace(' two-spotted spider mite', '')
        return name.lower().strip()

    def map_dataset_class_to_db(self, class_name: str) -> Tuple[str, Optional[str]]:
        """
        将数据集类名映射到数据库中的植物和病害 (保持简单映射逻辑)
        Args:
            class_name: 数据集类名 ("植物-病害", "植物___病害") 或 植物名
        Returns:
            (植物名, 病害名 或 None) 元组
        """
        if self.mapping_service: # 如果有 MappingService 则优先使用
             try:
                 return self.mapping_service.map_to_chinese(class_name)
             except Exception as e:
                 logger.error(f"调用 MappingService 出错: {e}，使用简单映射。")

        # 简单备用映射逻辑
        class_name_norm = class_name.replace('_', ' ') # 替换下划线为空格

        # 英文 -> 中文映射 (基于 plant_classes.json 推断)
        plant_map_en_zh = {
            "apple": "苹果", "blueberry": "蓝莓", "cherry": "樱桃", "corn": "玉米",
            "grape": "葡萄", "orange": "橙子", "peach": "桃子", "pepper bell": "甜椒", # 注意这里已替换下划线
            "potato": "土豆", "raspberry": "树莓", "soybean": "大豆", "squash": "西葫芦",
            "strawberry": "草莓", "tomato": "番茄"
        }
        disease_map_en_zh = {
            "apple scab": "黑星病", "black rot": "黑腐病", "cedar apple rust": "雪松苹果锈病",
            "healthy": "健康", "powdery mildew": "白粉病", "cercospora leaf spot gray leaf spot": "灰斑病",
            "common rust": "普通锈病", "northern leaf blight": "北方叶枯病", "esca (black measles)": "黑麻疹病",
            "leaf blight (isariopsis leaf spot)": "叶枯病", "haunglongbing (citrus greening)": "黄龙病",
            "bacterial spot": "细菌性斑点病", "early blight": "早疫病", "late blight": "晚疫病",
            "leaf scorch": "叶焦病", "leaf mold": "叶霉病", "septoria leaf spot": "斑枯病",
            "spider mites two-spotted spider mite": "二斑叶螨", "target spot": "靶斑病",
            "tomato mosaic virus": "花叶病毒病", "tomato yellow leaf curl virus": "黄化曲叶病毒病"
        }

        # 检查 "植物-病害" 中文格式
        if '-' in class_name:
            parts = class_name.split('-', 1)
            if len(parts) == 2:
                return parts[0].strip(), parts[1].strip()

        # 检查 "植物___病害" 英文格式
        if '___' in class_name_norm:
            parts = class_name_norm.split('___', 1)
            plant_en = parts[0].strip()
            disease_en = parts[1].strip()
            plant_zh = plant_map_en_zh.get(plant_en, plant_en) # 找不到映射则返回原样
            disease_zh = disease_map_en_zh.get(disease_en, disease_en if disease_en != "healthy" else "健康")
            return plant_zh, disease_zh

        # 如果都不是，尝试将整个输入视为植物名（中文或英文）
        plant_zh = plant_map_en_zh.get(class_name_norm, class_name) # 尝试英文映射，否则返回原输入
        return plant_zh, None


